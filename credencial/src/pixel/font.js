export const GLIFOS = Object.fromEntries(Object.entries(G).map(([k, v]) => [k, v.split(" ")]));
export const AVANCE = 6;

// Mayúsculas, sin tildes (salvo la Ñ) y solo con caracteres que el alfabeto conoce.
export function normalizar(texto) {
  return String(texto)
    .toUpperCase()
    .replace(/Ñ/g, "\u0001")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/\u0001/g, "Ñ")
    .split("")
    .filter((ch) => GLIFOS[ch])
    .join("");
}
export const anchoTexto = (t) => Math.max(0, normalizar(t).length * AVANCE - 1);
